package com.encapsulation;

public class Student {
	private String name;
	private int rollNum;
	
	//setter student data
	public void setName(String name) {
		this.name= name;
	}
	public void setRollNum(int rollNum) {
		this.rollNum = rollNum;
	}
	
	//getter student data
	public String getName() {
		return name;
	}
	public int getRollNum() {
		return rollNum;
	}

}

