package com.keywordAndDatatype;

public class Litrals {

	public static void main(String[] args) {
		int number = 45;
		double marks = 35.55;
		char grade = 'A';
		String name = "gayatri";
		boolean result = true;
		
		System.out.println("integer:"+number);
		System.out.println("float-point:"+marks);
		System.out.println("char:"+grade);
		System.out.println("string:"+name);
		System.out.println("boolean:"+result);
		
	}
}


// int    :  store integer value
// float  :  store decimal value
// char   :  represent single character in single quote
// string :  represent sequence of char i double quotes
// boolean:  represent logical value true or false 
